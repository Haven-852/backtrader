def column_label(name: str, table: Optional[str] = None) -> str:
    if table and table in TABLE_COLUMN_OVERRIDES:
        ov = TABLE_COLUMN_OVERRIDES[table].get(name)
        if ov:
            return ov
    return COLUMN_LABELS.get(name, name)


def enrich_columns(
    cols: List[Dict[str, Any]], table: Optional[str] = None
) -> List[Dict[str, Any]]:
    """为列信息附加中文 label，供前端展示 name：说明。"""
    out: List[Dict[str, Any]] = []
    for c in cols:
        name = c.get("name") or c.get("column_name") or ""
        item = dict(c)
        item["name"] = name
        item["label"] = column_label(name, table)
        out.append(item)
    return out
